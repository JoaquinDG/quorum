"""Build the human rubric-review worksheet from the data, not from memory.

    PYTHONPATH=src python3 evals/rubric_worksheet.py --out evals/RUBRIC_WORKSHEET.md

The adversarial model review (`rubric_review.py`) produced verdicts on 120
criteria. Nobody has read them. This turns them into something a person can
sit down and process, in batches, with a decision on every row.

What reading `RUBRIC_REVIEW.md` will not tell you, and this script exists to
surface: **every one of its findings was already acted on before it was
published, and not one of those actions has a recorded reason.**

The review ran against commit `8365d11`. The commit that published it,
`973c69c`, also removed 21 criteria and retagged 26 more, which is every
criterion the reviewer flagged. So the headline "44 of 120 mistagged, 19
unmeasurable" reads as a list of outstanding problems when it is in fact a
changelog for work already done, against a rubric that no longer exists.

That leaves the rubric in an odd state: correct, probably, and undocumented,
certainly. The worksheet's job is therefore ratification rather than triage.
Every change gets confirmed or reversed by a person, with a reason written
down, which is what should have happened the first time.

Batching is by criterion key, because the flags are not independent: 19 of
the 25 retags are the same key flagged the same way in 19 tasks. That is one
policy decision, not nineteen, and the difference is roughly thirty real
judgement calls instead of a hundred and twenty rows.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
from collections import defaultdict

HERE = os.path.dirname(__file__)
TASKS = os.path.join(HERE, "judgment_tasks.json")
REVIEW = os.path.join(HERE, "RUBRIC_REVIEW.json")

# The rubric state the review was written against, and the commit that
# silently remediated it. Recorded as SHAs rather than described, so every
# count below is checkable with `git show <sha>:evals/judgment_tasks.json`.
REVIEW_ERA_COMMIT = "8365d11"
REMEDIATION_COMMIT = "973c69c"


def tag_of(criterion) -> str:
    return "favours_deliberation" if criterion.get("favours_deliberation") else "neutral"


def review_era_tags() -> dict[tuple[str, str], str] | None:
    """Every (task, criterion) -> tag as it stood when the review ran.

    Read out of git rather than kept as a second copy on disk, so the counts
    in this worksheet derive from the repository's own history and cannot
    drift away from it. None outside a checkout, and the worksheet says so
    rather than guessing.
    """
    try:
        blob = subprocess.run(
            ["git", "show", f"{REVIEW_ERA_COMMIT}:evals/judgment_tasks.json"],
            cwd=os.path.join(HERE, ".."), capture_output=True, check=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        return None
    return {
        (t["key"], c["key"]): tag_of(c)
        for t in json.loads(blob)["tasks"]
        for c in t["criteria"]
    }


def build(tasks, review) -> list[str]:
    live = {(t["key"], c["key"]): c for t in tasks for c in t["criteria"]}
    verdicts = {
        (tk, c["key"]): c for tk, data in review.items() for c in data["criteria"]
    }
    era = review_era_tags()

    removed = sorted(set(era) - set(live)) if era else sorted(
        i for i in verdicts if i not in live
    )
    retagged = sorted(
        i for i in live if era and i in era and era[i] != tag_of(live[i])
    )
    unreviewed = sorted(i for i in live if i[0] not in review)
    # a never-reviewed criterion that was also retagged is already a Batch 1
    # row; listing it twice invites two contradictory decisions on one tag.
    unreviewed_only = [i for i in unreviewed if i not in retagged]
    unchanged = sorted(
        i for i in live if i not in retagged and i not in unreviewed
    )

    total_live = len(live)
    total_era = len(era) if era else "?"

    out: list[str] = []
    w = out.append

    w("# Rubric review worksheet: for human eyes")
    w("")
    w("| | |")
    w("|---|---|")
    w("| **Status** | `OPEN`. No human has processed this |")
    w("| **Reviewer of record** | (unsigned) |")
    w("| **Generated by** | `evals/rubric_worksheet.py`, from "
      "`judgment_tasks.json`, `RUBRIC_REVIEW.json`, and repo history |")
    w("")

    # ---- The correction ----------------------------------------------------
    w("## Read this first: the published figures are stale")
    w("")
    w("`RUBRIC_REVIEW.md` reports **44 of 120 criteria mistagged** and **19")
    w("unmeasurable**. Both describe a rubric that no longer exists, and both")
    w("read as open problems when they are not.")
    w("")
    w(f"The review ran against `{REVIEW_ERA_COMMIT}` ({total_era} criteria).")
    w(f"The very commit that published it, `{REMEDIATION_COMMIT}`, also:")
    w("")
    w(f"- **removed {len(removed)} criteria**, and")
    w(f"- **retagged {len(retagged)} more**")
    w("")
    w("which between them account for **every criterion the reviewer flagged**,")
    w("plus two in the one task it never looked at. No criterion *text* was")
    w("changed anywhere, so every rewrite the reviewer proposed was declined")
    w("without that being recorded either.")
    w("")
    w("| | |")
    w("|---|---|")
    w(f"| criteria at review time | {total_era} |")
    w(f"| criteria now | {total_live} |")
    w("| mistag flags still outstanding | **0** |")
    w("| unmeasurable flags still outstanding | **0** |")
    w(f"| changes made with a recorded reason | **0 of {len(removed) + len(retagged)}** |")
    w(f"| criteria never reviewed by anyone | {len(unreviewed)} |")
    w("")
    w("So the rubric is very likely *correct* and definitely *undocumented*.")
    w("The problem this worksheet solves is not triage, it is ratification:")
    w(f"{len(removed) + len(retagged)} undocumented changes need a person to confirm")
    w("or reverse each one and write down why.")
    w("")
    w("**Do not quote 44/120 or 19-unmeasurable again without this correction.**")
    w("The disclosure pack publishes the corrected figures.")
    w("")

    # ---- The rule ----------------------------------------------------------
    w("## The rule")
    w("")
    w("Every row gets a decision. For rows recording a change already made,")
    w("that is **confirm** or **reverse**. For rows still open, it is")
    w("**accept** / **fix** / **drop**.")
    w("")
    w("**Nothing is dropped silently.** A drop with no reason recorded is not a")
    w("drop, it is a deletion. The reason column is filled on the same pass as")
    w("the decision. This has already gone wrong once, across")
    w(f"{len(removed) + len(retagged)} criteria at once, which is why Batches 0")
    w("and 1 exist at all.")
    w("")
    w("Batches are independent. Stop after any one of them.")
    w("")

    # ---- Batch 0: removals -------------------------------------------------
    w("---")
    w("")
    w(f"## Batch 0: {len(removed)} criteria already removed. Ratify or reverse.")
    w("")
    w("The reviewer called these unmeasurable and it was, on the face of it,")
    w("right. But the removal was never recorded, so what exists today is a")
    w("rubric that quietly lost a sixth of itself.")
    w("")
    w("**Read the side effect before deciding, because it is not obvious.**")
    w("`calibrated` was tagged *neutral*. Removing it from every task is what")
    w("created the 7-task neutral-majority problem: before the removal all 20")
    w("tasks had a neutral-criteria majority, after it 13 do. The council's")
    w("whole two-tier disclosure plan is a response to a condition this edit")
    w("produced. Reversing it would dissolve that problem; it would also")
    w("reinstate 20 criteria a hostile reviewer called unscorable.")
    w("")
    w("| task | criterion | reviewer's objection | decision | reason (required) |")
    w("|---|---|---|---|---|")
    seen = set()
    for task_key, ckey in removed:
        v = verdicts.get((task_key, ckey))
        if v is None:
            why = "**never reviewed**, removed with no verdict either way"
        elif ckey in seen:
            why = "(as above)"
        else:
            why = v["why"].replace("|", "/")
        seen.add(ckey)
        w(f"| `{task_key}` | `{ckey}` | {why} | ☐ confirm ☐ reverse | |")
    w("")
    orphans = [i for i in removed if i not in verdicts]
    if orphans:
        w(f"**{len(orphans)} of these carried no verdict at all** "
          f"({', '.join('`%s.%s`' % i for i in orphans)}).")
        w("They belong to the one task the adversarial review skipped, so they")
        w("were removed on the strength of a pattern rather than a finding.")
        w("That is a thinner basis than the rest of this batch.")
        w("")
    w("**Shortcut:** one decision covers every `calibrated` row. Record it once")
    w("with its reason, tick the rest as following it, and decide the orphans")
    w("and `customer_risk` separately.")
    w("")

    # ---- Batch 1: retags, grouped ------------------------------------------
    families = defaultdict(list)
    for i in retagged:
        families[i[1]].append(i)
    ordered = sorted(families.items(), key=lambda kv: (-len(kv[1]), kv[0]))

    w("---")
    w("")
    w(f"## Batch 1: {len(retagged)} criteria already retagged. Ratify or reverse.")
    w("")
    w("Each of these was flagged as mistagged and then retagged to whatever the")
    w("reviewer said, with no reason recorded and no human in the loop. Adopting")
    w("a hostile reviewer's verdict wholesale is a defensible policy. It was not")
    w("a stated one.")
    w("")
    w(f"Grouped by criterion, because {len(ordered[0][1])} of the {len(retagged)}")
    w("are the same key flagged the same way. That group is one decision.")
    w("")

    n = 0
    for ckey, rows in ordered:
        n += 1
        judged = [i for i in rows if i in verdicts]
        blind = [i for i in rows if i not in verdicts]
        sample = verdicts[judged[0]] if judged else None
        w(f"### 1.{n}: `{ckey}` · {len(rows)} task"
          f"{'s' if len(rows) > 1 else ''}")
        w("")
        w(f"- was: **{era[rows[0]] if era else '?'}**")
        w(f"- now: **{tag_of(live[rows[0]])}**"
          + (" (the reviewer's verdict, applied as-is)" if judged else ""))
        w("")
        if sample:
            w(f"> {sample['why']}")
            w("")
        if blind:
            w(f"**{len(blind)} of these carried no verdict**"
              f" ({', '.join('`%s`' % i[0] for i in blind)}):"
              " the task was never reviewed, and the retag was applied to it")
            w("anyway as part of the pattern. Decide it on its own merits.")
            w("")
        if sample and sample.get("rewrite"):
            w("The reviewer also proposed a rewrite, which was **not** applied"
              " (no criterion text was changed anywhere in the remediation):")
            w("")
            w(f"> {sample['rewrite']}")
            w("")
        w("☐ **confirm** the retag  ☐ **reverse** it  "
          "☐ **fix** differently (adopt the rewrite, or write your own)  ☐ **drop**")
        w("")
        w("Reason (required):")
        w("")
        w("```")
        w("")
        w("```")
        w("")
        if len(rows) > 1:
            w(f"<details><summary>the {len(rows)} tasks, with a per-task override "
              "if the policy does not fit one of them</summary>")
            w("")
            w("| task | criterion text | override |")
            w("|---|---|---|")
            for i in rows:
                text = live[i]["text"].replace("|", "/")
                mark = "" if i in verdicts else " **(no verdict)**"
                w(f"| `{i[0]}`{mark} | {text} | ☐ follows policy ☐ other: |")
            w("")
            w("</details>")
            w("")

    # ---- Batch 2: never reviewed -------------------------------------------
    if unreviewed_only:
        task_key = unreviewed_only[0][0]
        w("---")
        w("")
        w(f"## Batch 2: {len(unreviewed_only)} criteria never reviewed by anyone")
        w("")
        w(f"The adversarial review covered 19 of 20 tasks. `{task_key}` was")
        w("skipped, so these carry no verdict at all: not confirmed fair, not")
        w("flagged, simply unexamined. They have been scored in every mock run")
        w("and would be scored in the live one.")
        w("")
        w("Either decide them here, or re-run `rubric_review.py` against this one")
        w("task first, which costs about a cent and gives you a verdict to react to.")
        w("")
        dupes = [i for i in unreviewed if i in retagged]
        if dupes:
            w(f"({', '.join('`%s`' % i[1] for i in dupes)} belongs to this task too,")
            w("but was retagged and is therefore decided in Batch 1. It is not")
            w("repeated here, so one tag cannot collect two contradictory decisions.)")
            w("")
        w("☐ re-run the model review for this task before deciding")
        w("")
        w("| criterion | tag | text | decision |")
        w("|---|---|---|---|")
        for i in unreviewed_only:
            text = live[i]["text"].replace("|", "/")
            w(f"| `{i[1]}` | {tag_of(live[i])} | {text} | ☐ accept ☐ fix ☐ drop |")
        w("")
        w("Reason for any drop or fix (required):")
        w("")
        w("```")
        w("")
        w("```")
        w("")

    # ---- Batch 3: unchanged ------------------------------------------------
    w("---")
    w("")
    w(f"## Batch 3: {len(unchanged)} criteria the reviewer looked at and left alone")
    w("")
    w("Listed so this worksheet covers the whole rubric rather than only the")
    w("parts something happened to. A reviewer told to be hostile read each of")
    w("these and declined to flag it, and none has been touched since.")
    w("")
    w("**Default is accept.** Skim, tick anything you disagree with, then sign")
    w("the batch off as a whole. Signing it off in one line is a valid outcome")
    w("and should be recorded as one rather than left blank.")
    w("")
    w("☐ **Batch accepted in full**. Signed: ____________  date: __________")
    w("")
    w(f"<details><summary>all {len(unchanged)} rows</summary>")
    w("")
    w("| task | criterion | tag | reviewer's note | pull out? |")
    w("|---|---|---|---|---|")
    for i in unchanged:
        v = verdicts.get(i)
        why = v["why"].replace("|", "/") if v else ""
        w(f"| `{i[0]}` | `{i[1]}` | {tag_of(live[i])} | {why} | ☐ |")
    w("")
    w("</details>")
    w("")

    # ---- Tally -------------------------------------------------------------
    w("---")
    w("")
    w("## Tally")
    w("")
    w("Fill in when the batches are done. This table is what the disclosure pack")
    w("cites, and it replaces the stale 44/120 figure wherever that appears.")
    w("")
    w("| | count |")
    w("|---|---|")
    w(f"| criteria at review time (`{REVIEW_ERA_COMMIT}`) | {total_era} |")
    w(f"| criteria now | {total_live} |")
    w(f"| removals ratified (Batch 0) | of {len(removed)} |")
    w("| removals reversed | |")
    w(f"| retags confirmed (Batch 1) | of {len(retagged)} |")
    w("| retags reversed or refixed | |")
    w(f"| never-reviewed criteria decided (Batch 2) | of {len(unreviewed_only)} |")
    w(f"| confirmed-fair batch signed off (Batch 3) | of {len(unchanged)} |")
    w("| **drops with a recorded reason** | **must equal total drops** |")
    w("")
    w("Criteria in the rubric after this pass: ______")
    w("")
    w("Tasks with a neutral-criteria majority after this pass: ______ of 20")
    w("")
    w("> That last number decides the disclosure partition. It is currently 13,")
    w("> and Batch 0 can move it.")
    w("")
    w("Sign-off: ____________________  date: __________")
    w("")
    w("Rubric SHA after edits: ____________________")
    w("")
    return out


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Build the rubric review worksheet.")
    parser.add_argument("--out", default=None)
    args = parser.parse_args(argv)

    tasks = json.load(open(TASKS, encoding="utf-8"))["tasks"]
    review = json.load(open(REVIEW, encoding="utf-8"))
    text = "\n".join(build(tasks, review))
    if args.out:
        with open(args.out, "w", encoding="utf-8") as handle:
            handle.write(text)
        print(f"written to {os.path.relpath(args.out)}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
