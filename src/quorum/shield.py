SHEET_FIELDS = ("position", "claims", "assumptions", "would_change_my_mind", "nuance")


def scan_sheet(sheet: Any, *, actor: str = "") -> tuple[Finding, ...]:
    """Scan every free-text field of an answer sheet, field by field.

    Per field rather than on the rendered whole, so a finding says *where* it
    was: "nuance" and "claim 3" are very different reports. `nuance` is the
    one worth naming explicitly, because it is the only field that reaches the
    arbiter unblinded and that no critic is permitted to answer.
    """
    findings: list[Finding] = []
    findings.extend(scan(getattr(sheet, "position", "") or "", where="position", actor=actor))
    for claim in getattr(sheet, "claims", ()) or ():
        findings.extend(
            scan(getattr(claim, "text", "") or "", where=f"claim {getattr(claim, 'number', '?')}", actor=actor)
        )
    for label in ("assumptions", "would_change_my_mind"):
        for i, item in enumerate(getattr(sheet, label, ()) or ()):
            findings.extend(scan(item or "", where=f"{label}[{i}]", actor=actor))
    findings.extend(scan(getattr(sheet, "nuance", "") or "", where="nuance", actor=actor))
    return tuple(findings)


def scan_objection(argument: str, *, actor: str = "", target: str = "") -> tuple[Finding, ...]:
    where = f"objection->{target}" if target else "objection"
    return scan(argument or "", where=where, actor=actor)


def scan_task(task: str) -> tuple[Finding, ...]:
    """The question itself is untrusted too.

    It is the one input that does not come from a model, which is exactly why
    it is easy to forget: a question pasted out of a ticket, an email or a
    retrieved document carries whatever was in that document, and round 1
    hands it to every student with no fence at all.
    """
    return scan(task or "", where="task", actor="system")
